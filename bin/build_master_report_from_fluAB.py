#!/usr/bin/env python3

"""
build_master_report_from_fluAB.py

Create a master influenza analysis report from a bwa_freebayes,
minimap2_clair3, or fluab2 run, plus read-level QC from SeqKit
seqstats outputs.

Inputs
------

    1. consensus_summary.csv
    2. typing.tsv
    3. nextclade.tsv
    4. input_seqstats.tsv
       (illumina_reads.input_seqstats.tsv or
        nanopore_reads.input_seqstats.tsv)
    5. trimmed_seqstats.tsv
    6. dehost_seqstats.tsv
    7. samplesheet.csv with sample,fastq_1,fastq_2,long_fastq

Consensus ID formats
--------------------

Two cid formats are accepted:

    bwa_freebayes / minimap2_clair3:
        <sample>-<tool>-seg_<N>-ref_<ACCESSION>
        e.g. flua_n_1-minimap2_clair3-seg_1-ref_PP664072

    fluab2 / FASTA-header style:
        <sample>-seg<N>|<SUBTYPE>
        e.g. flua_i_1-seg8|H3N2

Segment ID normalization
------------------------

In the output, every segN_id is written in the fluab2 style:

    <sample>-seg<N>|<SUBTYPE>

For cids that already carry a |SUBTYPE suffix (fluab2 style),
the subtype is taken from the cid. For cids that do not (tool
style), the subtype is taken from the ref_query-comment field
of consensus_summary.csv (field 4, pipe-delimited). This makes
seg1_id .. seg8_id directly comparable across reports produced
by different pipelines.

If neither source provides a subtype, the |SUBTYPE suffix is
omitted and the id is written as <sample>-seg<N>.

Design
------

Consensus sequences are generated by mapping reads to specific
reference genomes. Each consensus is therefore tied to that
reference's subtype. ref_subtype (from ref_query-comment) is
the grouping key.

Read QC
-------

seqstats.tsv files have one row per input FASTQ. For each
sample, we sum:

    num_seqs       -> *_num_reads
    sum_len        -> *_total_bases
    avg_len        -> *_avg_len (recomputed as total_bases / num_reads)

The three stages are:

    input_seqstats     -> input_*
    trimmed_seqstats   -> trimmed_*
    dehost_seqstats    -> dehosted_*

For paired-end Illumina samples, seqstats reports R1 and R2
separately, so the summed num_seqs is 2x the number of read
pairs. The script divides by 2 so the reported *_num_reads is
the number of read pairs, matching the convention used by most
read QC tools.

Percentages:

    trimmed_pct             = 100 * trimmed_num_reads / input_num_reads
    dehosted_pct_of_trimmed = 100 * dehosted_num_reads / trimmed_num_reads
    dehosted_pct_of_input   = 100 * dehosted_num_reads / input_num_reads

read_type
---------

For each sample, read_type is determined from the samplesheet:

    "paired"    Illumina paired-end (fastq_1 and fastq_2)
    "single"    Illumina single-end (fastq_1 only) or Nanopore
                (long_fastq only)
    "NA"        none of the above

A sample is either Illumina (fastq_1 / fastq_2) or Nanopore
(long_fastq). The samplesheet is expected to fill exactly one
of those two styles per row. Nanopore reads are single-end,
so they share the "single" label with Illumina SE.

Sample name detection
---------------------

Trimmed and dehosted seqstats filenames carry the sample name
directly. Two naming conventions are recognised:

    Illumina (fastp):
        <sample>_<read>.fastp[.clean].fastq.gz
        e.g. flua_i_1_1.fastp.fastq.gz

    Nanopore (chopper):
        <sample>.chopper[.clean].fastq.gz
        e.g. flua_n_1.chopper.clean.fastq.gz

Input seqstats filenames may or may not carry the sample name,
so the samplesheet is used to map input FASTQ basenames back
to sample names.

Without a samplesheet, input_* columns are "NA" and read_type
falls back to filename-based heuristics.
"""

import argparse
import csv
import re
from collections import defaultdict


SEGMENTS = ("1", "2", "3", "4", "5", "6", "7", "8")

TYPING_SEGMENTS = {"4", "6", "7"}
NEXTCLADE_SEGMENTS = {"4", "6"}

FLU_B_LINEAGES = {"Victoria", "Yamagata"}

# read_type values used in the output.
# Nanopore reads are single-end, so READ_TYPE_ONT shares the
# "single" label with Illumina single-end.
READ_TYPE_PAIRED = "paired"
READ_TYPE_SINGLE = "single"
READ_TYPE_ONT = "single"
READ_TYPE_NA = "NA"


READ_QC_COLUMNS = [
    "read_type",
    "input_num_reads",
    "input_total_bases",
    "input_avg_len",
    "trimmed_num_reads",
    "trimmed_total_bases",
    "trimmed_avg_len",
    "trimmed_pct",
    "dehosted_num_reads",
    "dehosted_total_bases",
    "dehosted_avg_len",
    "dehosted_pct_of_trimmed",
    "dehosted_pct_of_input",
]


TYPING_COLUMNS = [
    "typing",
    "typing_pident",
    "typing_qcov",
    "typing_evalue",
]


NEXTCLADE_GENE_COLUMNS = {
    "HA": {
        "clade": "clade",
        "proposedSubclade": "proposedSubclade",
        "subclade": "subclade",
        "qc.overallStatus": "nextclade_qc.overallStatus",
    },
    "NA": {
        "clade": "clade",
        "proposedSubclade": "proposedSubclade",
        "subclade": "subclade",
        "qc.overallStatus": "nextclade_qc.overallStatus",
    },
}


# bwa_freebayes / minimap2_clair3 style:
#   <sample>-<tool>-seg_<N>-ref_<ACCESSION>
CID_RE = re.compile(
    r"^(?P<sample>.+)-"
    r"(?P<tool>[A-Za-z0-9_]+)-seg_(?P<segment>\d+)"
    r"-ref_(?P<accession>[A-Za-z0-9_.]+)$"
)

# fluab2 / FASTA-header style:
#   <sample>-seg<N>|<SUBTYPE>
# The |SUBTYPE suffix is optional.
FASTA_CID_RE = re.compile(
    r"^(?P<sample>.+)-seg(?P<segment>\d+)"
    r"(?:\|(?P<subtype>[^|]+))?$"
)

SSEQID_RE = re.compile(
    r"^(?P<accession>[^~]+)~~(?P<segment>\d+)~~(?P<subtype>.+)$"
)

# Illumina trimmed/dehosted filenames (fastp):
#   <sample>_<read>.fastp[.clean].fastq.gz
FASTP_SAMPLE_RE = re.compile(
    r"^(?P<sample>.+?)_(?P<read>\d+)\.fastp\."
)

# Nanopore trimmed/dehosted filenames (chopper):
#   <sample>.chopper[.clean].fastq.gz
CHOPPER_SAMPLE_RE = re.compile(
    r"^(?P<sample>.+?)\.chopper(?:\.clean)?\.fastq\.gz$"
)

INPUT_FASTQ_RE = re.compile(
    r"^(?P<prefix>.+?)_R(?P<read>[12])(?:_\d+)?\.fastq\.gz$"
)


def parse_cid(cid):
    """
    Parse a consensus ID into sample, segment, accession, tool,
    and subtype.

    Two input formats are supported:

        1. bwa_freebayes / minimap2_clair3:
               <sample>-<tool>-seg_<N>-ref_<ACCESSION>
               e.g. flua_n_1-minimap2_clair3-seg_1-ref_PP664072

        2. fluab2 / FASTA-header style:
               <sample>-seg<N>|<SUBTYPE>
               e.g. flua_i_1-seg8|H3N2

    The returned segment is always a bare digit string ("1"
    through "8"), with any leading zeros stripped, so that
    seg1_id .. seg8_id mean the same thing regardless of which
    pipeline produced the cid.

    Returns a dict with keys sample, tool, segment, accession,
    subtype, or None if neither pattern matches.
    """

    match = CID_RE.match(cid)
    if match:
        return {
            "sample": match.group("sample"),
            "tool": match.group("tool"),
            "segment": str(int(match.group("segment"))),
            "accession": match.group("accession"),
            "subtype": None,
        }

    match = FASTA_CID_RE.match(cid)
    if match:
        return {
            "sample": match.group("sample"),
            "tool": None,
            "segment": str(int(match.group("segment"))),
            "accession": None,
            "subtype": match.group("subtype"),
        }

    return None


def normalize_segment_id(cid, consensus_row=None):
    """
    Rewrite a cid to the fluab2 / FASTA-header style:

        <sample>-seg<N>|<SUBTYPE>

    The subtype comes from parse_cid() if the cid already
    contains one (fluab2 style), otherwise from the
    ref_query-comment field of the consensus summary row
    (bwa_freebayes / minimap2_clair3 style).

    If neither source provides a subtype, the |SUBTYPE suffix
    is omitted, so the output is <sample>-seg<N>.
    """

    parsed = parse_cid(cid)
    if parsed is None:
        return cid   # unknown format; leave it alone

    sample = parsed["sample"]
    segment = parsed["segment"]

    subtype = parsed.get("subtype") or ""
    if not subtype and consensus_row is not None:
        subtype = parse_ref_comment(
            consensus_row.get("ref_query-comment", "")
        )

    if subtype:
        return f"{sample}-seg{segment}|{subtype}"
    return f"{sample}-seg{segment}"


def parse_sseqid(sseqid):
    match = SSEQID_RE.match(sseqid or "")
    if not match:
        return None
    return {
        "accession": match.group("accession"),
        "segment": match.group("segment"),
        "subtype": match.group("subtype").strip(),
    }


def parse_ref_comment(comment):
    fields = (comment or "").split("|")
    if len(fields) < 4:
        return ""
    return fields[3].strip()


def read_tsv(path):
    with open(path, "r", newline="") as in_f:
        return list(csv.DictReader(in_f, delimiter="\t"))


def read_csv(path):
    with open(path, "r", newline="") as in_f:
        return list(csv.DictReader(in_f, delimiter=","))


def read_consensus_summary(path):
    records = {}
    for row in read_csv(path):
        records[row["cid"]] = row
    return records


def read_typing(path):
    records = {}
    for row in read_tsv(path):
        qseqid = row["qseqid"]
        current = records.get(qseqid)
        if current is None:
            records[qseqid] = row
            continue
        try:
            if float(row["pident"]) > float(current["pident"]):
                records[qseqid] = row
        except ValueError:
            pass
    return records


def read_nextclade(path):
    records = {}
    for row in read_tsv(path):
        seqname = (row.get("seqName") or "").strip()
        if seqname:
            records[seqname] = row
    return records


def read_samplesheet(path):
    """
    Read a samplesheet CSV or TSV.

    Recognised columns (case-insensitive):

        sample, fastq_1, fastq_2, long_fastq

    A row is either Illumina (fastq_1, optionally fastq_2) or
    Nanopore (long_fastq). If both styles are present, Illumina
    wins and a warning is printed.

    Returns:
        fastq_sample_map: {fastq_basename: sample}
        read_type_map:    {sample: "paired" | "single" | "NA"}
    """

    if not path:
        return {}, {}

    with open(path, "r", newline="") as in_f:
        first_line = in_f.readline()
    delimiter = "\t" if "\t" in first_line else ","

    with open(path, "r", newline="") as in_f:
        reader = csv.DictReader(in_f, delimiter=delimiter)
        header_map = {name.lower(): name for name in (reader.fieldnames or [])}

        sample_col = header_map.get("sample")
        fq1_col = header_map.get("fastq_1")
        fq2_col = header_map.get("fastq_2")
        long_col = header_map.get("long_fastq")

        if sample_col is None:
            raise ValueError(
                f"Samplesheet {path} must contain a 'sample' column. "
                f"Found: {reader.fieldnames}"
            )

        fastq_sample_map = {}
        read_type_map = {}

        for row in reader:
            sample = (row.get(sample_col) or "").strip()
            if not sample:
                continue

            fq1 = (row.get(fq1_col) or "").strip() if fq1_col else ""
            fq2 = (row.get(fq2_col) or "").strip() if fq2_col else ""
            long_fastq = (row.get(long_col) or "").strip() if long_col else ""

            if fq1.lower() == "na":
                fq1 = ""
            if fq2.lower() == "na":
                fq2 = ""
            if long_fastq.lower() == "na":
                long_fastq = ""

            has_illumina = bool(fq1 or fq2)
            has_nanopore = bool(long_fastq)

            if has_illumina and has_nanopore:
                print(
                    f"WARNING: sample {sample!r} has both Illumina and "
                    f"Nanopore reads in the samplesheet; using Illumina.",
                    flush=True,
                )
                has_nanopore = False

            if has_illumina:
                if fq1 and fq2:
                    read_type = READ_TYPE_PAIRED
                elif fq1:
                    read_type = READ_TYPE_SINGLE
                else:
                    read_type = READ_TYPE_NA

                if fq1:
                    fastq_sample_map[fq1.split("/")[-1]] = sample
                if fq2:
                    fastq_sample_map[fq2.split("/")[-1]] = sample

            elif has_nanopore:
                read_type = READ_TYPE_ONT
                fastq_sample_map[long_fastq.split("/")[-1]] = sample

            else:
                read_type = READ_TYPE_NA

            read_type_map[sample] = read_type

    print(
        f"Read {len(read_type_map)} samples from {path} "
        f"({len(fastq_sample_map)} FASTQ mappings)",
        flush=True,
    )
    return fastq_sample_map, read_type_map


def seqstats_sample_name(file_field, fastq_sample_map):
    """
    Return the sample name for a seqstats row.

    Two naming conventions are recognised:

        Illumina (fastp):
            <sample>_<read>.fastp[.clean].fastq.gz
            e.g. flua_i_1_1.fastp.fastq.gz

        Nanopore (chopper):
            <sample>.chopper[.clean].fastq.gz
            e.g. flua_n_1.chopper.clean.fastq.gz

    The samplesheet map is a fallback for input FASTQs whose
    basenames don't carry the sample name (e.g. sequencing
    facility names).
    """

    basename = (file_field or "").strip()
    if not basename:
        return ""

    match = FASTP_SAMPLE_RE.match(basename)
    if match:
        return match.group("sample")

    match = CHOPPER_SAMPLE_RE.match(basename)
    if match:
        return match.group("sample")

    if basename in fastq_sample_map:
        return fastq_sample_map[basename]

    return ""


def read_seqstats(path, fastq_sample_map, read_type_map):
    """
    Read a seqstats TSV and aggregate per sample.

    For paired samples, seqstats reports R1 and R2 separately,
    so the summed num_seqs is 2x the number of read pairs. The
    reported *_num_reads is the number of read pairs (summed
    num_seqs // 2 for paired, unchanged for single).
    """

    aggregated = defaultdict(lambda: {"num_seqs": 0, "sum_len": 0})

    for row in read_tsv(path):
        sample = seqstats_sample_name(row.get("file", ""), fastq_sample_map)
        if not sample:
            continue

        try:
            num_seqs = int(float(row.get("num_seqs", "0") or 0))
            sum_len = int(float(row.get("sum_len", "0") or 0))
        except ValueError:
            continue

        aggregated[sample]["num_seqs"] += num_seqs
        aggregated[sample]["sum_len"] += sum_len

    for sample, agg in aggregated.items():
        if agg["num_seqs"] > 0:
            agg["avg_len"] = agg["sum_len"] / agg["num_seqs"]
        else:
            agg["avg_len"] = 0.0

        # Paired: report read pairs, not individual reads.
        if read_type_map.get(sample) == READ_TYPE_PAIRED:
            agg["num_seqs"] = agg["num_seqs"] // 2

    return dict(aggregated)


def add_read_qc_columns(
    row, sample, seqstats_by_stage, read_type_map,
):
    input_stats = seqstats_by_stage["input"].get(sample, {})
    trimmed_stats = seqstats_by_stage["trimmed"].get(sample, {})
    dehosted_stats = seqstats_by_stage["dehosted"].get(sample, {})

    row["read_type"] = read_type_map.get(sample, READ_TYPE_NA)

    def set_stats(prefix, stats):
        if not stats:
            row[f"{prefix}_num_reads"] = "NA"
            row[f"{prefix}_total_bases"] = "NA"
            row[f"{prefix}_avg_len"] = "NA"
            return
        row[f"{prefix}_num_reads"] = stats["num_seqs"]
        row[f"{prefix}_total_bases"] = stats["sum_len"]
        row[f"{prefix}_avg_len"] = f"{stats['avg_len']:.1f}"

    set_stats("input", input_stats)
    set_stats("trimmed", trimmed_stats)
    set_stats("dehosted", dehosted_stats)

    def pct(numerator, denominator):
        try:
            return f"{100.0 * float(numerator) / float(denominator):.2f}"
        except (TypeError, ValueError, ZeroDivisionError):
            return "NA"

    input_reads = input_stats.get("num_seqs")
    trimmed_reads = trimmed_stats.get("num_seqs")
    dehosted_reads = dehosted_stats.get("num_seqs")

    row["trimmed_pct"] = pct(trimmed_reads, input_reads)
    row["dehosted_pct_of_trimmed"] = pct(dehosted_reads, trimmed_reads)
    row["dehosted_pct_of_input"] = pct(dehosted_reads, input_reads)


def build_report(
    consensus_summary,
    typing,
    nextclade,
    seqstats_by_stage,
    read_type_map,
    flu_db_ver,
    nf_fluab_ver,
):

    cid_meta = {}
    for cid in consensus_summary:
        parsed = parse_cid(cid)
        if parsed is None:
            print(f"WARNING: cannot parse cid: {cid!r}", flush=True)
            continue
        if parsed["segment"] not in SEGMENTS:
            print(
                f"WARNING: invalid segment {parsed['segment']!r} "
                f"in cid: {cid!r}",
                flush=True,
            )
            continue
        cid_meta[cid] = parsed

    cid_ref_subtype = {}
    for cid, row in consensus_summary.items():
        subtype = parse_ref_comment(row.get("ref_query-comment", ""))
        if subtype:
            cid_ref_subtype[cid] = subtype

    grouped = defaultdict(list)
    for cid, meta in cid_meta.items():
        ref_subtype = cid_ref_subtype.get(cid)
        if not ref_subtype:
            continue
        grouped[(meta["sample"], ref_subtype)].append(cid)

    rows = []
    for (sample, ref_subtype) in sorted(grouped):
        sample_ref_subtypes = sorted({
            rs for (s, rs) in grouped if s == sample
        })
        ref_subtype_index = sample_ref_subtypes.index(ref_subtype) + 1

        row = {
            "sample": sample,
            "ref_subtype_index": ref_subtype_index,
            "ref_subtype": ref_subtype,
        }

        segment_cid = {}
        for cid in grouped[(sample, ref_subtype)]:
            meta = cid_meta[cid]
            segment_cid[meta["segment"]] = cid

        for segment in SEGMENTS:
            cid = segment_cid.get(segment)
            if cid is None:
                add_missing_segment(row, segment)
                continue
            add_segment_record(
                row=row,
                segment=segment,
                cid=cid,
                consensus_row=consensus_summary[cid],
                typing=typing,
                nextclade=nextclade,
            )

        row["predicted_type_or_lineage"] = (
            derive_predicted_type_or_lineage(row)
        )
        add_coverage_summary(row)

        add_read_qc_columns(
            row=row,
            sample=sample,
            seqstats_by_stage=seqstats_by_stage,
            read_type_map=read_type_map,
        )

        row["flu_db_ver"] = flu_db_ver
        row["nf_fluab_ver"] = nf_fluab_ver
        rows.append(row)

    return rows


def add_missing_segment(row, segment):
    prefix = f"seg{segment}"
    row[f"{prefix}_id"] = "NA"
    for column in ("length", "numreads", "completeness", "meandepth"):
        row[f"{prefix}_{column}"] = "NA"
    if segment in TYPING_SEGMENTS:
        for column in TYPING_COLUMNS:
            row[f"{prefix}_{column}"] = "NA"
    if segment in NEXTCLADE_SEGMENTS:
        row[f"{prefix}_clade"] = "NA"
        row[f"{prefix}_proposedSubclade"] = "NA"
        row[f"{prefix}_subclade"] = "NA"
        row[f"{prefix}_nextclade_qc.overallStatus"] = "NA"


def add_segment_record(row, segment, cid, consensus_row, typing, nextclade):
    prefix = f"seg{segment}"

    row[f"{prefix}_id"] = normalize_segment_id(cid, consensus_row)

    row[f"{prefix}_length"] = consensus_row.get("gene_length", "NA")
    row[f"{prefix}_numreads"] = consensus_row.get("numreads_mapped", "NA")
    row[f"{prefix}_completeness"] = consensus_row.get("pct_completeness", "NA")
    row[f"{prefix}_meandepth"] = consensus_row.get("meandepth", "NA")

    if segment in TYPING_SEGMENTS:
        typing_hit = typing.get(cid, {})
        sseq_meta = parse_sseqid(typing_hit.get("sseqid", ""))
        row[f"{prefix}_typing"] = (
            sseq_meta["subtype"] if sseq_meta else "NA"
        )
        row[f"{prefix}_typing_pident"] = typing_hit.get("pident", "NA")
        row[f"{prefix}_typing_qcov"] = typing_hit.get("qcovs", "NA")
        row[f"{prefix}_typing_evalue"] = typing_hit.get("evalue", "NA")

    if segment in NEXTCLADE_SEGMENTS:
        nextclade_hit = nextclade.get(cid, {})
        mapping = NEXTCLADE_GENE_COLUMNS["HA" if segment == "4" else "NA"]
        for source_column, target_suffix in mapping.items():
            row[f"{prefix}_{target_suffix}"] = (
                nextclade_hit.get(source_column, "NA") or "NA"
            )


def derive_predicted_type_or_lineage(row):
    ha = (row.get("seg4_typing") or "NA").strip()
    na = (row.get("seg6_typing") or "NA").strip()

    ha_missing = ha in ("", "NA")
    na_missing = na in ("", "NA")

    if not ha_missing and ha in FLU_B_LINEAGES:
        return ha
    if ha_missing and na_missing:
        return "NA"
    if ha_missing:
        return na
    if na_missing:
        return ha
    return f"{ha}{na}"


def add_coverage_summary(row):
    segment_count = len(SEGMENTS)
    for metric in ("completeness", "meandepth"):
        total = 0.0
        for segment in SEGMENTS:
            raw = row.get(f"seg{segment}_{metric}", "NA")
            if raw in (None, "", "NA"):
                continue
            try:
                total += float(raw)
            except ValueError:
                continue
        row[f"avg_genome_{metric}"] = f"{total / segment_count:.2f}"


def get_output_columns():
    columns = ["sample"]
    columns.extend(READ_QC_COLUMNS)
    columns.extend([
        "ref_subtype_index",
        "ref_subtype",
        "predicted_type_or_lineage",
    ])
    for segment in SEGMENTS:
        prefix = f"seg{segment}"
        columns.extend([
            f"{prefix}_id",
            f"{prefix}_length",
            f"{prefix}_numreads",
            f"{prefix}_completeness",
            f"{prefix}_meandepth",
        ])
        if segment in TYPING_SEGMENTS:
            columns.extend([
                f"{prefix}_typing",
                f"{prefix}_typing_pident",
                f"{prefix}_typing_qcov",
                f"{prefix}_typing_evalue",
            ])
        if segment in NEXTCLADE_SEGMENTS:
            columns.extend([
                f"{prefix}_clade",
                f"{prefix}_proposedSubclade",
                f"{prefix}_subclade",
                f"{prefix}_nextclade_qc.overallStatus",
            ])
    columns.extend([
        "avg_genome_completeness",
        "avg_genome_meandepth",
        "flu_db_ver",
        "nf_fluab_ver",
    ])
    return columns


def write_report(rows, output):
    columns = get_output_columns()
    with open(output, "w", newline="") as out_f:
        writer = csv.DictWriter(
            out_f, fieldnames=columns, delimiter="\t",
            extrasaction="ignore",
        )
        writer.writeheader()
        for row in rows:
            writer.writerow({c: row.get(c, "NA") for c in columns})


def main():
    parser = argparse.ArgumentParser(
        description=(
            "Create a master influenza report from bwa_freebayes, "
            "minimap2_clair3, or fluab2 outputs, grouped by "
            "(sample, reference subtype), with read-level QC from "
            "seqstats. segN_id is normalized to the fluab2 style "
            "<sample>-seg<N>|<SUBTYPE>."
        )
    )
    parser.add_argument("--consensus-summary", required=True)
    parser.add_argument("--typing", required=True)
    parser.add_argument("--nextclade", required=True)
    parser.add_argument("--input-seqstats", required=True)
    parser.add_argument("--trimmed-seqstats", required=True)
    parser.add_argument("--dehosted-seqstats", required=True)
    parser.add_argument(
        "--samplesheet", required=True,
        help="CSV/TSV with sample,fastq_1,fastq_2,long_fastq columns. "
             "A row is either Illumina (fastq_1/fastq_2) or Nanopore "
             "(long_fastq).",
    )
    parser.add_argument("--flu-db-ver", required=True)
    parser.add_argument("--nf-fluab-ver", required=True)
    parser.add_argument("-o", "--output", required=True)
    args = parser.parse_args()

    consensus_summary = read_consensus_summary(args.consensus_summary)
    typing = read_typing(args.typing)
    nextclade = read_nextclade(args.nextclade)

    fastq_sample_map, read_type_map = read_samplesheet(args.samplesheet)

    seqstats_by_stage = {
        "input": read_seqstats(
            args.input_seqstats, fastq_sample_map, read_type_map,
        ),
        "trimmed": read_seqstats(
            args.trimmed_seqstats, fastq_sample_map, read_type_map,
        ),
        "dehosted": read_seqstats(
            args.dehosted_seqstats, fastq_sample_map, read_type_map,
        ),
    }

    rows = build_report(
        consensus_summary=consensus_summary,
        typing=typing,
        nextclade=nextclade,
        seqstats_by_stage=seqstats_by_stage,
        read_type_map=read_type_map,
        flu_db_ver=args.flu_db_ver,
        nf_fluab_ver=args.nf_fluab_ver,
    )

    write_report(rows, args.output)


if __name__ == "__main__":
    main()
